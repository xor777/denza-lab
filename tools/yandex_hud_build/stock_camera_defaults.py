#!/usr/bin/env python3
"""Emit portable constants from the original GBL manager's decoded default table snapshot."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'research/yandex-hud-renderer/stock-camera-defaults.json'
TARGET = ROOT / 'libraries/hud-link/src/main/java/dev/denza/hudlink/camera/StockCameraDefaults.java'
TABLES = ('actionZoom', 'endZoom', 'complexZoom', 'baseZoom', 'keypointPitch', 'basePitch')
FIELDS = ('roadClass', 'formway', 'curvature', 'zoomLevel', 'screenType')


def number(value):
    return 'Float.NaN' if value is None else '(float)' + repr(float(value))


def generate():
    data = json.loads(SOURCE.read_text())
    lines = ['package dev.denza.hudlink.camera;', '',
             '// Generated by tools/yandex_hud_build/stock_camera_defaults.py; edit its pinned JSON input.',
             '// An independent original-manager default snapshot, not a live-car cloud configuration.',
             'final class StockCameraDefaults {',
             '    static final StockCameraRules.Rule[][] TABLES = {']
    for name in TABLES:
        lines.append('        { // ' + name)
        for row in data['tables'][name]['rows']:
            target = row.get('targetZoom', row.get('targetPitch'))
            args = [str(row['index']), number(target), number(row.get('lowerZoom')), number(row.get('upperZoom')),
                    str(row.get('effectDistanceM') if row.get('effectDistanceM') is not None else -1)]
            for field, groups in row['conditions'].items():
                for group in groups:
                    if group['nativeLogicType'] != 1:
                        raise ValueError('Unverified native boolean group')
                    for condition in group['conditions']:
                        args.append('new StockCameraRules.Condition(' + ', '.join([
                            str(FIELDS.index(field)), str(condition['nativeOpType']),
                            *[number(value) for value in condition['values']]]) + ')')
            lines.append('            new StockCameraRules.Rule(' + ', '.join(args) + '),')
        lines.append('        },')
    lines += ['    };', '}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if TARGET.read_text() != result:
            raise SystemExit('Stock camera constants differ from the pinned snapshot')
    else:
        TARGET.write_text(result)
